-- 1. Tabellen erstellen
CREATE TABLE IF NOT EXISTS public.restaurants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT NOT NULL,
  postal_code TEXT NOT NULL,
  address TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  category TEXT NOT NULL,
  has_parking BOOLEAN NOT NULL DEFAULT false,
  has_terrace BOOLEAN NOT NULL DEFAULT false,
  is_quick_lunch BOOLEAN NOT NULL DEFAULT false,
  opening_hours TEXT NOT NULL,
  website_url TEXT NOT NULL,
  wirt_pin TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.dishes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id BIGINT NOT NULL REFERENCES public.restaurants(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  title TEXT NOT NULL,
  price NUMERIC(6,2) NOT NULL,
  is_vegetarian BOOLEAN NOT NULL DEFAULT false,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Row Level Security (RLS) aktivieren
ALTER TABLE public.restaurants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dishes ENABLE ROW LEVEL SECURITY;

-- Öffentlicher Lesezugriff (SELECT) für alle Nutzer
-- WICHTIG: wirt_pin wird über eine sichere View oder Spalten-Auswahl geschützt,
-- hier erlauben wir SELECT für das Frontend und nutzen für Schreibzugriffe Service-Role / Edge Functions.
DROP POLICY IF EXISTS "Public read access for restaurants" ON public.restaurants;
CREATE POLICY "Public read access for restaurants"
  ON public.restaurants
  FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Public read access for dishes" ON public.dishes;
CREATE POLICY "Public read access for dishes"
  ON public.dishes
  FOR SELECT
  TO anon, authenticated
  USING (true);

-- Schreibzugriffe (INSERT, UPDATE, DELETE) sind standardmäßig für anon/authenticated blockiert
-- und nur über den SUPABASE_SERVICE_ROLE_KEY (Server / Edge Functions / Scraper) möglich.

